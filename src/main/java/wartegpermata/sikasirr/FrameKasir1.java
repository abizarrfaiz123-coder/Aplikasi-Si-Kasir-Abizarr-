    private void HapusItemTerakhirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_HapusItemTerakhirActionPerformed
        // TODO add your handling code here:
          if (transaksi.kosong()) {
        JOptionPane.showMessageDialog(this, "Belum ada transaksi");
        return;
}

        int pilihan = JOptionPane.showConfirmDialog(this,
        "Apakah yakin ingin menghapus item terakhir?",
        "Konfirmasi", JOptionPane.YES_NO_OPTION);

        if (pilihan == JOptionPane.YES_OPTION) {
        transaksi.hapusitemterakhir();

        double totalbaru = transaksi.hitungTotal();
        txtTotal.setText(String.valueOf((long) totalbaru));

        JOptionPane.showMessageDialog(this, "Item terakhir sukses dihapus");
}     
    }//GEN-LAST:event_HapusItemTerakhirActionPerformed

